OK, NO = T("تصرف جميل", "✅"), T("تصرف غير جميل", "❌")


def good_bad(lv, good, bad, k=2, q="ما التصرف الجميل وما التصرف غير الجميل؟"):
    for i in range(k):
        r = rng("gb", lv.id, i)
        g, b = good[:], bad[:]
        r.shuffle(g)
        r.shuffle(b)
        items = [(x, 0) for x in g[:3]] + [(x, 1) for x in b[:3]]
        r.shuffle(items)
        lv.add(sorting(q, [OK, NO], items))


def sc(lv, q, good, bads, hint=HINTS[1], k=3, sk=None):
    lv.add(pick(q, good, bads, k=k, seed=lv.id, hint=hint, sk=sk))


def pages(*ps):
    return [{"e": [E(x) for x in e], "x": t, "s": t} for e, t in ps]


